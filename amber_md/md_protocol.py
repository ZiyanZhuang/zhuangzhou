"""
AMBER MD Protocol — tleap, MD input files, run/analysis scripts.
Shahrokh et al., J. Comp. Chem. (2011) 10-stage equilibration protocol.
"""

import os


def _write_file(path, content):
    with open(path, 'w', encoding='utf-8') as f:
        f.write(content)


def generate_tleap_input(output_dir, pdb_name, state, params_dir,
                         axial_cys_resid, hem_resid, prmtop_name, inpcrd_name):
    """Generate tleap.in for system building.

    Returns path to tleap.in.
    """
    frcmod_name = f"{state}.frcmod"

    content = f"""# tleap input for CYP + Heme ({state}) system
# Parameters: Shahrokh et al., J. Comp. Chem. (2011)
# Auto-generated by zhuangzhou.amber_md

# Load force fields
source leaprc.protein.ff19SB
source leaprc.water.tip3p
source leaprc.gaff

# Load heme parameters ({state})
loadamberparams {params_dir}/{frcmod_name}

# Load HEM and CYP residue templates
HEM = loadmol2 {params_dir}/HEM.mol2
CYP = loadmol2 {params_dir}/CYP.mol2

# Set CYP head/tail for peptide chain connectivity
set CYP head CYP.1.N
set CYP tail CYP.1.C
set CYP.1 connect0 CYP.1.N
set CYP.1 connect1 CYP.1.C

# Load prepared PDB
mol = loadpdb {output_dir}/{pdb_name}

# Create Fe-S bond (Fe-N bonds are already in HEM.mol2 template - DO NOT add them!)
bond mol.{axial_cys_resid}.SG mol.{hem_resid}.FE

# Check for problems
check mol

# Solvate in truncated octahedron TIP3P box (12 A buffer)
solvateoct mol TIP3PBOX 12.0

# Neutralize with counterions
addionsrand mol Na+ 0
addionsrand mol Cl- 0

# Final check
check mol
charge mol

# Save topology and coordinates
saveamberparm mol {output_dir}/{prmtop_name} {output_dir}/{inpcrd_name}

quit
"""
    tleap_path = os.path.join(output_dir, "tleap.in")
    _write_file(tleap_path, content)
    return tleap_path


def generate_md_inputs(output_dir, state='CPDI', prod_ns=10.0):
    """Generate all MD input files following Shahrokh et al. protocol.

    10 stages: 2 min + 1 heating + 5 cyclic equil + 1 final equil + 1 production.
    Returns path to md_input/ directory.
    """
    md_dir = os.path.join(output_dir, "md_input")
    os.makedirs(md_dir, exist_ok=True)

    mask_all_solute = "'!(:WAT,Na+,Cl-)'"
    mask_ca_heme = "'@CA | :HEM | :CYP&@SG'"

    if state == 'CPDI':
        mask_fe_coord = "'@CA | :HEM@FE,NA,NB,NC,ND,O1 | :CYP&@SG'"
    elif state == 'DIOXY':
        mask_fe_coord = "'@CA | :HEM@FE,NA,NB,NC,ND,O1,O2 | :CYP&@SG'"
    else:
        mask_fe_coord = "'@CA | :HEM@FE,NA,NB,NC,ND | :CYP&@SG'"

    # Stage 1: Min solvent
    _write_file(os.path.join(md_dir, "01_min_solvent.in"),
                f"""Minimization: solvent only, protein+heme restrained 500 kcal
 &cntrl
  imin=1,
  maxcyc=1000,
  ncyc=500,
  ntb=1,
  ntr=1,
  restraintmask={mask_all_solute},
  restraint_wt=500.0,
  cut=9.0,
  ntpr=100,
 /
""")

    # Stage 2: Min Ca+heme
    _write_file(os.path.join(md_dir, "02_min_calpha.in"),
                f"""Minimization: Ca+heme restrained 25 kcal
 &cntrl
  imin=1,
  maxcyc=1000,
  ncyc=500,
  ntb=1,
  ntr=1,
  restraintmask={mask_ca_heme},
  restraint_wt=25.0,
  cut=9.0,
  ntpr=100,
 /
""")

    # Stage 3: Heating NVT (0->300K, 100ps)
    _write_file(os.path.join(md_dir, "03_heat_nvt.in"),
                f"""Heating: 0 -> 300 K over 100 ps (NVT), Ca restrained 25 kcal
 &cntrl
  imin=0,
  irest=0, ntx=1,
  nstlim=50000, dt=0.002,
  ntc=2, ntf=2,
  ntt=3, gamma_ln=0.2,
  tempi=0.0, temp0=300.0,
  ntb=1, ntp=0,
  ntr=1,
  restraintmask={mask_ca_heme},
  restraint_wt=25.0,
  cut=9.0,
  ntpr=500, ntwx=500, ntwr=5000,
  nmropt=1,
  ig=-1,
  ioutfm=1, ntxo=2,
 /
 &wt type='TEMP0', istep1=0, istep2=50000,
   value1=0.0, value2=300.0,
 /
 &wt type='END',
 /
""")

    # Stages 4-8: Cyclic equilibration (min + MD per cycle)
    forces = [5, 4, 3, 2, 1]
    stage_nums = ['04', '05', '06', '07', '08']

    for num, force in zip(stage_nums, forces):
        _write_file(os.path.join(md_dir, f"{num}_equil_{force}.in"),
                    f"""Equilibration: min step, Ca+heme restrained {force} kcal
 &cntrl
  imin=1,
  maxcyc=1000,
  ncyc=500,
  ntb=1,
  ntr=1,
  restraintmask={mask_ca_heme},
  restraint_wt={force}.0,
  cut=9.0,
  ntpr=100,
 /
""")
        # irest=0, ntx=1 because follows minimization
        _write_file(os.path.join(md_dir, f"{num}b_equil_{force}_md.in"),
                    f"""Equilibration MD: 300 K, NPT, Ca+heme restrained {force} kcal, 50 ps
 &cntrl
  imin=0,
  irest=0, ntx=1,
  nstlim=25000, dt=0.002,
  ntc=2, ntf=2,
  ntt=3, gamma_ln=1.0,
  tempi=300.0, temp0=300.0,
  ntb=2, ntp=1, barostat=2,
  pres0=1.0, taup=2.0,
  ntr=1,
  restraintmask={mask_ca_heme},
  restraint_wt={force}.0,
  cut=9.0,
  ntpr=500, ntwx=500, ntwr=5000,
  ig=-1,
  ioutfm=1, ntxo=2,
 /
""")

    # Stage 9: Final density equilibration (500ps, Fe-coord restraints)
    _write_file(os.path.join(md_dir, "09_equil_05.in"),
                f"""Final Equilibration: 300 K, NPT, Fe-coordination restrained 0.5 kcal, 500 ps
 &cntrl
  imin=0,
  irest=1, ntx=5,
  nstlim=250000, dt=0.002,
  ntc=2, ntf=2,
  ntt=3, gamma_ln=1.0,
  temp0=300.0,
  ntb=2, ntp=1, barostat=2,
  pres0=1.0, taup=2.0,
  ntr=1,
  restraintmask={mask_fe_coord},
  restraint_wt=0.5,
  cut=9.0,
  ntpr=500, ntwx=500, ntwr=5000,
  ig=-1,
  ioutfm=1, ntxo=2,
 /
""")

    # Stage 10: Production
    prod_steps = int(prod_ns * 1e6 / 2)  # dt=0.002 ps
    _write_file(os.path.join(md_dir, "10_prod.in"),
                f"""Production MD: 300 K, NPT, no restraints, {prod_ns} ns
 &cntrl
  imin=0,
  irest=1, ntx=5,
  nstlim={prod_steps}, dt=0.002,
  ntc=2, ntf=2,
  ntt=3, gamma_ln=1.0,
  temp0=300.0,
  ntb=2, ntp=1, barostat=2,
  pres0=1.0, taup=2.0,
  ntr=0,
  cut=9.0,
  ntpr=5000, ntwx=5000, ntwr=50000,
  ig=-1,
  ioutfm=1, ntxo=2,
 /
""")

    return md_dir


def generate_run_script(output_dir, prmtop, inpcrd):
    """Generate bash script to run all MD stages with pmemd.cuda.

    Returns path to run_md.sh.
    """
    script = f"""#!/bin/bash
#==============================================================================
# CYP + Heme MD Protocol (auto-generated by zhuangzhou.amber_md)
# Following: Shahrokh et al., J. Comp. Chem. (2011)
#==============================================================================
set -e

source ~/amber25/amber.sh

WORKDIR="{output_dir}"
INPUT="${{WORKDIR}}/md_input"
TOP="${{WORKDIR}}/{prmtop}"
CRD="${{WORKDIR}}/{inpcrd}"
REF="${{WORKDIR}}/{inpcrd}"

cd "$WORKDIR"
mkdir -p md_output
cd md_output

ENGINE="pmemd.cuda"

echo "[1/16] Minimization: solvent only"
$ENGINE -O -i ${{INPUT}}/01_min_solvent.in -o 01_min_solvent.out \\
  -p ${{TOP}} -c ${{CRD}} -ref ${{REF}} -r 01_min_solvent.rst7

echo "[2/16] Minimization: Ca+heme 25 kcal"
$ENGINE -O -i ${{INPUT}}/02_min_calpha.in -o 02_min_calpha.out \\
  -p ${{TOP}} -c 01_min_solvent.rst7 -ref ${{REF}} -r 02_min_calpha.rst7

echo "[3/16] Heating 0->300K (100ps NVT)"
$ENGINE -O -i ${{INPUT}}/03_heat_nvt.in -o 03_heat_nvt.out \\
  -p ${{TOP}} -c 02_min_calpha.rst7 -ref ${{REF}} -r 03_heat_nvt.rst7 -x 03_heat_nvt.nc

PREV_RST="03_heat_nvt.rst7"
STEP=4
for FORCE in 5 4 3 2 1; do
    NUM=$(printf "%02d" $STEP)
    echo "[${{STEP}}/16] Min + Equil: ${{FORCE}} kcal restraint"

    MIN_IN="${{NUM}}_equil_${{FORCE}}.in"
    MD_IN="${{NUM}}b_equil_${{FORCE}}_md.in"

    $ENGINE -O -i ${{INPUT}}/${{MIN_IN}} -o ${{NUM}}a_min_${{FORCE}}.out \\
      -p ${{TOP}} -c ${{PREV_RST}} -ref ${{REF}} -r ${{NUM}}a_min_${{FORCE}}.rst7

    $ENGINE -O -i ${{INPUT}}/${{MD_IN}} -o ${{NUM}}b_equil_${{FORCE}}.out \\
      -p ${{TOP}} -c ${{NUM}}a_min_${{FORCE}}.rst7 -ref ${{REF}} \\
      -r ${{NUM}}b_equil_${{FORCE}}.rst7 -x ${{NUM}}b_equil_${{FORCE}}.nc

    PREV_RST="${{NUM}}b_equil_${{FORCE}}.rst7"
    STEP=$((STEP+1))
done

echo "[14/16] Density equil (0.5 kcal, 500 ps)"
$ENGINE -O -i ${{INPUT}}/09_equil_05.in -o 09_equil_05.out \\
  -p ${{TOP}} -c ${{PREV_RST}} -ref ${{REF}} -r 09_equil_05.rst7 -x 09_equil_05.nc

echo "[15/16] Production MD"
$ENGINE -O -i ${{INPUT}}/10_prod.in -o 10_prod.out \\
  -p ${{TOP}} -c 09_equil_05.rst7 -r 10_prod.rst7 -x 10_prod.nc

echo ""
echo "All stages completed!"
echo "  Trajectory: md_output/10_prod.nc"
echo "  Restart:    md_output/10_prod.rst7"
"""
    path = os.path.join(output_dir, "run_md.sh")
    _write_file(path, script)
    return path


def generate_analysis_scripts(output_dir, prmtop, axial_cys_resid, hem_resid,
                              state='CPDI'):
    """Generate cpptraj analysis script and Python plotting script.

    Returns (analyze_sh_path, plot_py_path).
    """
    if state == 'CPDI':
        extra_dist = f"""
# Fe=O (Compound I oxo)
distance fe_o :{hem_resid}@FE :{hem_resid}@O1 out ${{OUTDIR}}/fe_o_dist.dat"""
    elif state == 'DIOXY':
        extra_dist = f"""
# Fe-O1 and Fe-O2 (dioxygenated)
distance fe_o1 :{hem_resid}@FE :{hem_resid}@O1 out ${{OUTDIR}}/fe_o1_dist.dat
distance fe_o2 :{hem_resid}@FE :{hem_resid}@O2 out ${{OUTDIR}}/fe_o2_dist.dat"""
    else:
        extra_dist = ""

    cpptraj_script = f"""#!/bin/bash
# Trajectory analysis for CYP-heme MD
# Auto-generated by zhuangzhou.amber_md

source ~/amber25/amber.sh

WORKDIR="{output_dir}"
TOP="${{WORKDIR}}/{prmtop}"
TRAJ="${{WORKDIR}}/md_output/10_prod.nc"
OUTDIR="${{WORKDIR}}/analysis"
mkdir -p ${{OUTDIR}}

cpptraj <<EOF
parm ${{TOP}}
trajin ${{TRAJ}}

# Fe-S distance
distance fe_s :{axial_cys_resid}@SG :{hem_resid}@FE out ${{OUTDIR}}/fe_s_dist.dat
{extra_dist}

# Fe-N distances (porphyrin)
distance fe_na :{hem_resid}@FE :{hem_resid}@NA out ${{OUTDIR}}/fe_na_dist.dat
distance fe_nb :{hem_resid}@FE :{hem_resid}@NB out ${{OUTDIR}}/fe_nb_dist.dat
distance fe_nc :{hem_resid}@FE :{hem_resid}@NC out ${{OUTDIR}}/fe_nc_dist.dat
distance fe_nd :{hem_resid}@FE :{hem_resid}@ND out ${{OUTDIR}}/fe_nd_dist.dat

# Protein RMSD (Ca, mass-weighted)
rms first :1-{hem_resid - 1}@CA out ${{OUTDIR}}/rmsd_ca.dat mass

# Heme RMSD (heavy atoms, fitted to Ca)
rms first :1-{hem_resid - 1}@CA
rms first :{hem_resid}&!@H= out ${{OUTDIR}}/rmsd_heme.dat mass

# RMSF by residue
rms first :1-{hem_resid - 1}@CA
atomicfluct :1-{hem_resid - 1}@CA out ${{OUTDIR}}/rmsf_ca.dat byres

# Radius of gyration
radgyr :1-{hem_resid - 1} out ${{OUTDIR}}/radgyr.dat mass

run

# Export PDB frames
clear all
parm ${{TOP}}

# First frame
trajin ${{TRAJ}} 1 1
autoimage
strip :WAT,Na+,Cl-
trajout ${{OUTDIR}}/frame_first.pdb pdb
run
clear trajin

# Last frame
trajin ${{TRAJ}} lastframe
autoimage
strip :WAT,Na+,Cl-
trajout ${{OUTDIR}}/frame_last.pdb pdb
run
clear trajin

# Full trajectory PDB (solute only)
trajin ${{TRAJ}}
autoimage
strip :WAT,Na+,Cl-
trajout ${{OUTDIR}}/prod_traj.pdb pdb
run
EOF

echo "Analysis complete. Results in ${{OUTDIR}}/"
"""
    analyze_path = os.path.join(output_dir, "analyze.sh")
    _write_file(analyze_path, cpptraj_script)

    # Pre-MD structure extraction
    pre_md_script = f"""#!/bin/bash
# Extract pre-MD initial structure
source ~/amber25/amber.sh
WORKDIR="{output_dir}"
cpptraj <<EOF
parm ${{WORKDIR}}/{prmtop}
trajin ${{WORKDIR}}/{prmtop.replace('.prmtop', '.inpcrd')}
autoimage
strip :WAT,Na+,Cl-
trajout ${{WORKDIR}}/analysis/pre_md_initial.pdb pdb
run
EOF
"""
    _write_file(os.path.join(output_dir, "extract_initial.sh"), pre_md_script)

    # Python plotting script
    plot_script = f"""#!/usr/bin/env python3
\"\"\"Plot MD analysis results. Auto-generated by zhuangzhou.amber_md.\"\"\"
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import os

base = "{output_dir}/analysis"
dt_ns = 0.01  # 10 ns / 1000 frames (adjust if ntwx differs)

def load_dat(f):
    d = np.loadtxt(f, skiprows=1)
    return d[:,0] * dt_ns, d[:,1]

def savefig(fig, name):
    fig.savefig(os.path.join(base, name + '.png'), dpi=200, bbox_inches='tight')
    plt.close(fig)
    print(f"  Saved {{name}}.png")

# Fe-S distance
fig, ax = plt.subplots(figsize=(8, 4))
t, v = load_dat(os.path.join(base, 'fe_s_dist.dat'))
ax.plot(t, v, 'b-', alpha=0.7, lw=0.6)
ax.axhline(2.565, color='r', ls='--', lw=1.2, label='Ref: 2.565 A')
ax.set(xlabel='Time (ns)', ylabel='Distance (A)', title='Fe-S(Cys) Distance')
ax.legend()
savefig(fig, 'fe_s_distance')

# Fe=O distance (if exists)
fe_o_file = os.path.join(base, 'fe_o_dist.dat')
if os.path.exists(fe_o_file):
    fig, ax = plt.subplots(figsize=(8, 4))
    t, v = load_dat(fe_o_file)
    ax.plot(t, v, 'g-', alpha=0.7, lw=0.6)
    ax.axhline(1.639, color='r', ls='--', lw=1.2, label='Ref: 1.639 A')
    ax.set(xlabel='Time (ns)', ylabel='Distance (A)', title='Fe=O (Oxo) Distance')
    ax.legend()
    savefig(fig, 'fe_o_distance')

# Fe-N distances
fig, ax = plt.subplots(figsize=(8, 4))
for name, color in [('fe_na', 'C0'), ('fe_nb', 'C1'), ('fe_nc', 'C2'), ('fe_nd', 'C3')]:
    f = os.path.join(base, f'{{name}}_dist.dat')
    if os.path.exists(f):
        t, v = load_dat(f)
        ax.plot(t, v, color=color, alpha=0.5, lw=0.5, label=f'Fe-{{name[-2:].upper()}}')
ax.axhline(2.029, color='r', ls='--', lw=1.2, label='Ref: 2.029 A')
ax.set(xlabel='Time (ns)', ylabel='Distance (A)', title='Fe-N (Porphyrin) Distances')
ax.legend(fontsize=10)
savefig(fig, 'fe_n_distances')

# RMSD (protein + heme)
fig, ax = plt.subplots(figsize=(8, 4))
t, rmsd_ca = load_dat(os.path.join(base, 'rmsd_ca.dat'))
ax.plot(t, rmsd_ca, 'k-', alpha=0.7, lw=0.6, label='Protein Ca')
heme_f = os.path.join(base, 'rmsd_heme.dat')
if os.path.exists(heme_f):
    _, rmsd_heme = load_dat(heme_f)
    ax.plot(t, rmsd_heme, 'r-', alpha=0.7, lw=0.6, label='Heme (heavy)')
ax.set(xlabel='Time (ns)', ylabel='RMSD (A)', title='RMSD: Protein vs Heme')
ax.legend()
savefig(fig, 'rmsd_protein_heme')

# Radius of gyration
fig, ax = plt.subplots(figsize=(8, 4))
rog = np.loadtxt(os.path.join(base, 'radgyr.dat'), skiprows=1)
ax.plot(rog[:,0] * dt_ns, rog[:,1], 'm-', alpha=0.7, lw=0.6)
ax.set(xlabel='Time (ns)', ylabel='RoG (A)', title='Radius of Gyration')
savefig(fig, 'radius_of_gyration')

# RMSF
fig, ax = plt.subplots(figsize=(10, 4))
rmsf = np.loadtxt(os.path.join(base, 'rmsf_ca.dat'), skiprows=1)
ax.plot(rmsf[:,0], rmsf[:,1], 'c-', lw=0.8)
ax.axvline({axial_cys_resid}, color='r', ls='--', alpha=0.7, lw=1, label='Axial Cys')
ax.set(xlabel='Residue Number', ylabel='RMSF (A)', title='Ca RMSF by Residue')
ax.legend()
savefig(fig, 'rmsf_by_residue')

# Statistics summary
print("\\n" + "=" * 60)
print("Fe Coordination Statistics")
print("=" * 60)
for name, ref in [('fe_s_dist.dat', 2.565), ('fe_o_dist.dat', 1.639),
                   ('fe_na_dist.dat', 2.029), ('fe_nb_dist.dat', 2.029),
                   ('fe_nc_dist.dat', 2.029), ('fe_nd_dist.dat', 2.029)]:
    f = os.path.join(base, name)
    if os.path.exists(f):
        _, vals = load_dat(f)
        label = name.replace('_dist.dat', '').upper().replace('_', '-')
        print(f"  {{label:<8s}} Mean={{np.mean(vals):.3f}} Std={{np.std(vals):.3f}} Ref={{ref:.3f}}")

_, rmsd = load_dat(os.path.join(base, 'rmsd_ca.dat'))
print(f"\\n  Ca RMSD:  Mean={{np.mean(rmsd):.3f}} A")
print(f"  RoG:      Mean={{np.mean(rog[:,1]):.3f}} A")
print("\\nAll plots saved.")
"""
    plot_path = os.path.join(output_dir, "plot_analysis.py")
    _write_file(plot_path, plot_script)

    return analyze_path, plot_path
