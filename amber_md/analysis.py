def _gen_standard_script(
    topology: str,
    trajectory: str,
    out_dir: str,
    ligand_resname: str,
    ligand_resid: int,
    active_residues: list[str],
    catalytic_residues: list[str] | None,
) -> str:
    """Generate cpptraj script for standard RMSD/RMSF/Rg/distance analysis."""
    active_mask = _make_res_mask(active_residues)
    lig_mask = f":{ligand_resid}"

    # catalytic distance pairs: each catalytic residue → ligand
    dist_lines = []
    if catalytic_residues:
        for cr in catalytic_residues:
            m = re.search(r"(\d+)", cr)
            if m:
                rid = m.group(1)
                dist_lines.append(
                    f"distance dist_{cr} :{rid}@CA {lig_mask}&!@H= out {out_dir}/dist_{cr}.dat"
                )

    return f"""\
parm {topology}
trajin {trajectory}

autoimage

# --- RMSD ---
rms first :1-{ligand_resid - 1}@CA out {out_dir}/rmsd_backbone.dat mass
rms ref_active first {active_mask}&!@H= out {out_dir}/rmsd_active.dat mass
rms ref_lig first {lig_mask}&!@H= out {out_dir}/rmsd_ligand.dat mass nofit

# --- RMSF ---
rms first :1-{ligand_resid - 1}@CA
atomicfluct :1-{ligand_resid - 1}@CA out {out_dir}/rmsf_ca.dat byres

# --- Rg ---
radgyr :1-{ligand_resid - 1} out {out_dir}/rog.dat mass

# --- B-factor ---
rms first :1-{ligand_resid - 1}@CA
atomicfluct :1-{ligand_resid - 1}@CA out {out_dir}/bfactor.dat byres bfactor

# --- Key distances ---
{chr(10).join(dist_lines)}

run
"""


def _gen_hbond_script(
    topology: str,
    trajectory: str,
    out_dir: str,
    ligand_resid: int,
    active_residues: list[str],
    frame_range: tuple[int, int] | None = None,
) -> str:
    """Generate cpptraj script for H-bond analysis (direct + water bridges)."""
    active_mask = _make_res_mask(active_residues)
    lig_mask = f":{ligand_resid}"
    prot_mask = f":1-{ligand_resid - 1}"

    frame_spec = ""
    if frame_range:
        frame_spec = f" {frame_range[0]} {frame_range[1]}"

    return f"""\
parm {topology}
trajin {trajectory}{frame_spec}

autoimage

# --- Direct H-bonds: active-site residues ↔ ligand ---
hbond hb_direct donormask {lig_mask} acceptormask {active_mask} out {out_dir}/hbond_direct.dat avgout {out_dir}/hbond_direct_avg.dat
hbond hb_accept donormask {active_mask} acceptormask {lig_mask} out {out_dir}/hbond_accept.dat avgout {out_dir}/hbond_accept_avg.dat

# --- Water-bridged H-bonds ---
hbond hb_wb_lig bridgeout {out_dir}/water_bridge.dat \
  donormask {lig_mask} acceptormask {prot_mask} \
  bridgeresonly solventdonor :WAT solventacceptor :WAT@O \
  avgout {out_dir}/hbond_wb_avg.dat

hbond hb_wb_prot bridgeout {out_dir}/water_bridge_prot.dat \
  donormask {prot_mask} acceptormask {lig_mask} \
  bridgeresonly solventdonor :WAT solventacceptor :WAT@O \
  avgout {out_dir}/hbond_wb_prot_avg.dat

# --- Ligand → all protein (for discovery) ---
hbond hb_nic_donor donormask {lig_mask} acceptormask {prot_mask} \
  out {out_dir}/hbond_nic_donor.dat avgout {out_dir}/hbond_nic_donor_avg.dat
hbond hb_nic_acceptor donormask {prot_mask} acceptormask {lig_mask} \
  out {out_dir}/hbond_nic_acceptor.dat avgout {out_dir}/hbond_nic_acceptor_avg.dat

run
"""


def _gen_clustering_script(
    topology: str,
    trajectory: str,
    out_dir: str,
    cluster_residues: list[str],
    ligand_resid: int,
    n_clusters: int = 5,
    frame_range: tuple[int, int] | None = None,
    prefix: str = "clust",
) -> str:
    """Generate cpptraj K-means clustering script on active-site residues + ligand."""
    res_mask = _make_res_mask(cluster_residues)
    lig_mask = f":{ligand_resid}"
    combined_mask = f"({res_mask}|{lig_mask})&!@H="

    frame_spec = ""
    if frame_range:
        frame_spec = f" {frame_range[0]} {frame_range[1]}"

    return f"""\
parm {topology}
trajin {trajectory}{frame_spec}

autoimage

rms first :1-{ligand_resid - 1}@CA

cluster kmeans clusters {n_clusters} \
  rms {combined_mask} \
  sievetoframe \
  summary {out_dir}/{prefix}_summary.dat \
  info {out_dir}/{prefix}_info.dat \
  repout {out_dir}/{prefix}_centroid repfmt pdb \
  clusterout {out_dir}/{prefix}_assign.dat

run
"""


def _gen_extract_script(
    topology: str,
    trajectory: str,
    out_dir: str,
    centroid_frame: int,
    ligand_resid: int,
    qm_residues: list[str] | None = None,
) -> str:
    """Generate cpptraj script to extract centroid PDB and optional QM region."""
    lig_mask = f":{ligand_resid}"

    qm_block = ""
    if qm_residues:
        qm_mask = _make_res_mask(qm_residues)
        qm_block = f"""
# --- QM region extraction ---
clear trajin
trajin {trajectory} {centroid_frame} {centroid_frame}
autoimage
strip !({qm_mask}|{lig_mask})
trajout {out_dir}/qm_region.pdb pdb
run
"""

    return f"""\
parm {topology}
trajin {trajectory} {centroid_frame} {centroid_frame}

autoimage

# Full system without solvent
strip :WAT,Na+,Cl-,K+
trajout {out_dir}/centroid_nosolv.pdb pdb

run

# --- Closest waters ---
clear all
parm {topology}
trajin {trajectory} {centroid_frame} {centroid_frame}
autoimage
closest 10 {lig_mask} closestout {out_dir}/closest_waters.dat
trajout {out_dir}/centroid_with_waters.pdb pdb
run
{qm_block}
"""


