def run_protein_ligand_analysis(
    work_dir: str,
    topology: str = "complex.prmtop",
    trajectory: str = "md_output/08_prod.nc",
    ligand_resname: str = "LIG",
    ligand_resid: int | None = None,
    catalytic_residues: list[str] | None = None,
    pocket_residues: list[str] | None = None,
    stable_frame_range: tuple[int, int] | None = None,
    n_clusters: int = 5,
    extract_qm: bool = True,
    qm_residues: list[str] | None = None,
    wsl: bool = True,
) -> dict:
    """Run comprehensive post-MD analysis for a protein–ligand system.

    Generates cpptraj scripts, executes them, parses results, and returns
    a structured dictionary with all findings.

    Args:
        work_dir:            MD run directory (contains topology + md_output/)
        topology:            Topology filename (relative to work_dir)
        trajectory:          Production trajectory (relative to work_dir)
        ligand_resname:      3-letter ligand residue name (e.g. 'NIC')
        ligand_resid:        Ligand residue number (auto-detect if None)
        catalytic_residues:  User-specified catalytic residues ['CYS16', 'HIP54', ...]
        pocket_residues:     Actual pocket residues for clustering
                             (if None, falls back to catalytic_residues)
        stable_frame_range:  (start, end) frame numbers for stable phase
                             (if None, uses full trajectory)
        n_clusters:          Number of K-means clusters
        extract_qm:          Whether to extract QM region PDBs
        qm_residues:         Residues to include in QM region
                             (if None, uses pocket_residues)
        wsl:                 Execute cpptraj via WSL (Windows)

    Returns:
        dict with keys: standard, hbond, clustering, structures, report_path
    """
    if not os.path.isdir(work_dir):
        return {"error": f"Directory not found: {work_dir}"}

    # Resolve paths
    wsl_dir = (
        work_dir.replace("\\", "/").replace("E:", "/mnt/e").replace("e:", "/mnt/e")
    )
    topo_path = f"{wsl_dir}/{topology}"
    traj_path = f"{wsl_dir}/{trajectory}"

    # Determine ligand residue number if not provided
    if ligand_resid is None:
        ligand_resid = _detect_ligand_resid(work_dir, topology, ligand_resname)
        if ligand_resid is None:
            return {"error": f"Could not detect residue number for {ligand_resname}"}
        log.info("Detected %s as residue %d", ligand_resname, ligand_resid)

    # Use pocket_residues for clustering, fall back to catalytic_residues
    cluster_res = pocket_residues or catalytic_residues
    if not cluster_res:
        return {
            "error": "Either pocket_residues or catalytic_residues must be provided"
        }

    # QM residues default to pocket residues
    if qm_residues is None:
        qm_residues = pocket_residues or catalytic_residues

    # Create output directories
    base_out = os.path.join(work_dir, "analysis")
    dirs = {
        "standard": os.path.join(base_out, "standard"),
        "hbond": os.path.join(base_out, "hbond"),
        "clustering": os.path.join(base_out, "clustering"),
        "structures": os.path.join(base_out, "structures"),
    }
    for d in dirs.values():
        os.makedirs(d, exist_ok=True)

    wsl_dirs = {
        k: v.replace("\\", "/").replace("E:", "/mnt/e").replace("e:", "/mnt/e")
        for k, v in dirs.items()
    }

    results = {}

    # ------------------------------------------------------------------
    # 1. Standard analysis (RMSD, RMSF, Rg, distances)
    # ------------------------------------------------------------------
    log.info("Step 1/4: Standard analysis ...")
    active_res_for_standard = pocket_residues if pocket_residues else catalytic_residues
    script = _gen_standard_script(
        topo_path,
        traj_path,
        wsl_dirs["standard"],
        ligand_resname,
        ligand_resid,
        active_res_for_standard,
        catalytic_residues,
    )
    _run_cpptraj_wsl(script, work_dir, "01_standard.cpptraj")

    # Parse standard outputs
    std_files = {}
    for fn in os.listdir(dirs["standard"]):
        if fn.endswith(".dat"):
            std_files[fn] = os.path.join(dirs["standard"], fn)
    results["standard"] = {"output_dir": dirs["standard"], "files": std_files}

    # ------------------------------------------------------------------
    # 2. H-bond analysis
    # ------------------------------------------------------------------
    log.info("Step 2/4: H-bond analysis ...")
    hb_frame_range = stable_frame_range
    script = _gen_hbond_script(
        topo_path,
        traj_path,
        wsl_dirs["hbond"],
        ligand_resid,
        active_res_for_standard,
        hb_frame_range,
    )
    _run_cpptraj_wsl(script, work_dir, "02_hbond.cpptraj")

    # Parse H-bond results
    hbond_results = {}
    for fn in [
        "hbond_direct_avg.dat",
        "hbond_accept_avg.dat",
        "hbond_nic_donor_avg.dat",
        "hbond_nic_acceptor_avg.dat",
    ]:
        fp = os.path.join(dirs["hbond"], fn)
        if os.path.isfile(fp):
            hbond_results[fn.replace("_avg.dat", "")] = _parse_hbond_avg(fp)

    # Parse water bridges
    wb_file = os.path.join(dirs["hbond"], "water_bridge.dat")
    if os.path.isfile(wb_file):
        hbond_results["water_bridges_file"] = wb_file

    results["hbond"] = {
        "output_dir": dirs["hbond"],
        "interactions": hbond_results,
        "frame_range": hb_frame_range,
    }

    # ------------------------------------------------------------------
    # 3. Clustering
    # ------------------------------------------------------------------
    log.info("Step 3/4: Clustering ...")
    script = _gen_clustering_script(
        topo_path,
        traj_path,
        wsl_dirs["clustering"],
        cluster_res,
        ligand_resid,
        n_clusters,
        stable_frame_range,
        prefix="clust",
    )
    _run_cpptraj_wsl(script, work_dir, "03_clustering.cpptraj")

    # Parse cluster summary
    summary_file = os.path.join(dirs["clustering"], "clust_summary.dat")
    clusters = []
    if os.path.isfile(summary_file):
        clusters = _parse_cluster_summary(summary_file)

    results["clustering"] = {
        "output_dir": dirs["clustering"],
        "n_clusters": n_clusters,
        "frame_range": stable_frame_range,
        "residues_used": cluster_res,
        "clusters": clusters,
    }

    # Find most populated cluster centroid
    best_cluster = max(clusters, key=lambda c: c["frac"]) if clusters else None

    # ------------------------------------------------------------------
    # 4. Extract representative structures
    # ------------------------------------------------------------------
    if extract_qm and best_cluster is not None:
        log.info(
            "Step 4/4: Extracting structures (centroid frame %d) ...",
            best_cluster["centroid_frame"],
        )
        script = _gen_extract_script(
            topo_path,
            traj_path,
            wsl_dirs["structures"],
            best_cluster["centroid_frame"],
            ligand_resid,
            qm_residues,
        )
        _run_cpptraj_wsl(script, work_dir, "04_extract.cpptraj")

        struct_files = {}
        for fn in os.listdir(dirs["structures"]):
            struct_files[fn] = os.path.join(dirs["structures"], fn)

        results["structures"] = {
            "output_dir": dirs["structures"],
            "centroid_frame": best_cluster["centroid_frame"],
            "files": struct_files,
        }
    else:
        results["structures"] = {"note": "Extraction skipped"}

    # ------------------------------------------------------------------
    # 5. Generate report
    # ------------------------------------------------------------------
    report_path = _generate_analysis_report(
        work_dir,
        results,
        ligand_resname,
        ligand_resid,
        catalytic_residues,
        pocket_residues,
        stable_frame_range,
    )
    results["report_path"] = report_path

    # Save machine-readable result
    json_path = os.path.join(base_out, "analysis_result.json")
    with open(json_path, "w", encoding="utf-8") as fh:
        json.dump(results, fh, indent=2, default=str)
    results["json_path"] = json_path

    log.info("Analysis complete → %s", report_path)
    return results


def _detect_ligand_resid(
    work_dir: str, topology: str, ligand_resname: str
) -> int | None:
    """Use cpptraj to find the residue number of *ligand_resname*."""
    wsl_dir = (
        work_dir.replace("\\", "/").replace("E:", "/mnt/e").replace("e:", "/mnt/e")
    )
    script = f"parm {wsl_dir}/{topology}\nresinfo *\nquit\n"
    out = _run_cpptraj_wsl(script, work_dir, "_detect_lig.cpptraj")
    for line in out.splitlines():
        if ligand_resname in line:
            m = re.search(r"^\s*(\d+)", line)
            if m:
                return int(m.group(1))
    return None


def _generate_analysis_report(
    work_dir: str,
    results: dict,
    ligand_resname: str,
    ligand_resid: int,
    catalytic_residues: list[str] | None,
    pocket_residues: list[str] | None,
    stable_frame_range: tuple[int, int] | None,
) -> str:
    """Generate a Markdown analysis report."""
    lines = [
        "# AMBER MD Post-Production Analysis Report",
        "",
        f"**Work directory:** `{work_dir}`",
        f"**Ligand:** {ligand_resname} (residue {ligand_resid})",
        "",
    ]

    if catalytic_residues:
        lines.append(f"**Catalytic residues:** {', '.join(catalytic_residues)}")
    if pocket_residues:
        lines.append(f"**Pocket residues:** {', '.join(pocket_residues)}")
    if stable_frame_range:
        lines.append(
            f"**Stable phase:** frames {stable_frame_range[0]}–{stable_frame_range[1]}"
        )
    lines.append("")

    # Standard outputs
    lines.append("## 1. Standard Analysis")
    std = results.get("standard", {})
    if "files" in std:
        for fn in sorted(std["files"]):
            lines.append(f"- `{fn}`")
    lines.append("")

    # H-bond
    lines.append("## 2. H-Bond Network")
    hb = results.get("hbond", {})
    interactions = hb.get("interactions", {})
    for key, entries in interactions.items():
        if isinstance(entries, list) and entries:
            lines.append(f"\n### {key}")
            lines.append("| Name | Frac | AvgDist(Å) | AvgAngle(°) |")
            lines.append("|------|------|------------|-------------|")
            for e in sorted(entries, key=lambda x: -x["frac"])[:15]:
                lines.append(
                    f"| {e['name']} | {e['frac']:.3f} | {e['avgdist']:.2f} | {e['avgangle']:.1f} |"
                )
    lines.append("")

    # Clustering
    lines.append("## 3. Clustering")
    clust = results.get("clustering", {})
    if clust.get("clusters"):
        lines.append(f"\nResidues: {', '.join(clust.get('residues_used', []))}")
        lines.append(f"K = {clust['n_clusters']}")
        lines.append("")
        lines.append("| Cluster | Frames | Fraction | AvgDist(Å) | Centroid |")
        lines.append("|---------|--------|----------|------------|----------|")
        for c in clust["clusters"]:
            lines.append(
                f"| C{c['cluster']} | {c['frames']} | {c['frac']:.3f} | "
                f"{c['avgdist']:.2f} | frame {c['centroid_frame']} |"
            )
    lines.append("")

    # Structures
    lines.append("## 4. Extracted Structures")
    st = results.get("structures", {})
    if "files" in st:
        lines.append(f"\nCentroid frame: {st.get('centroid_frame')}")
        for fn in sorted(st["files"]):
            lines.append(f"- `{fn}`")
    lines.append("")

    report_path = os.path.join(work_dir, "analysis", "ANALYSIS_REPORT.md")
    with open(report_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    return report_path
