def _run_cpptraj_wsl(
    script_text: str, work_dir: str, script_name: str = "analysis.cpptraj"
) -> str:
    """Write *script_text* inside *work_dir* and execute via cpptraj in WSL.

    Returns cpptraj stdout+stderr as a string.
    """
    wsl_work = (
        work_dir.replace("\\", "/").replace("E:", "/mnt/e").replace("e:", "/mnt/e")
    )
    script_path = os.path.join(work_dir, script_name)
    with open(script_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(script_text)
    wsl_script = f"{wsl_work}/{script_name}"
    cmd = f'wsl bash -lc "source ~/amber25/amber.sh && cpptraj -i {wsl_script}"'
    log.info("cpptraj  %s", script_name)
    result = subprocess.run(
        cmd, shell=True, capture_output=True, text=True, timeout=7200
    )
    if result.returncode != 0:
        raise RuntimeError(f"cpptraj failed ({script_name}):\n{result.stderr[-2000:]}")
    return result.stdout + result.stderr


def _parse_dat(filepath: str, skip_header: bool = True) -> list[dict]:
    """Parse a cpptraj .dat file → list of {col0: ..., col1: ..., ...}."""
    rows = []
    with open(filepath, encoding="utf-8") as fh:
        for i, line in enumerate(fh):
            if skip_header and i == 0 and line.startswith("#"):
                continue
            parts = line.split()
            if not parts:
                continue
            rows.append(
                [float(x) if "." in x or "E" in x.upper() else int(x) for x in parts]
            )
    return rows


def _parse_hbond_avg(filepath: str) -> list[dict]:
    """Parse hbond avgout file → list of dicts with acceptor, donor, frac, avgdist, avgangle."""
    results = []
    with open(filepath, encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) < 5:
                continue
            results.append(
                {
                    "name": parts[0],
                    "frames": int(parts[1]),
                    "frac": float(parts[2]),
                    "avgdist": float(parts[3]),
                    "avgangle": float(parts[4]),
                }
            )
    return results


def _parse_cluster_summary(filepath: str) -> list[dict]:
    """Parse cpptraj cluster summary → list of {cluster, frames, frac, avgdist, centroid_frame}."""
    clusters = []
    with open(filepath, encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            parts = line.split()
            if len(parts) < 5:
                continue
            clusters.append(
                {
                    "cluster": int(parts[0]),
                    "frames": int(parts[1]),
                    "frac": float(parts[2]),
                    "avgdist": float(parts[3]),
                    "centroid_frame": int(parts[4]),
                }
            )
    return clusters


def _make_res_mask(residues: list[str]) -> str:
    """Convert ['CYS16','HIP54',...] → ':16,54,...' (residue-number mask)."""
    nums = []
    for r in residues:
        m = re.search(r"(\d+)", r)
        if m:
            nums.append(m.group(1))
    return ":" + ",".join(nums)


def _make_ca_mask(residues: list[str]) -> str:
    """Convert ['CYS16','HIP54',...] → ':16,54,@CA' (CA atoms of those residues)."""
    return _make_res_mask(residues) + "@CA"


