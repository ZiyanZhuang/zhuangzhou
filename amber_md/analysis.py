"""Analysis script generation for Amber MD trajectories.

Contains:
  1. CYP-heme specific analysis  (run_cyp_heme_analysis)
  2. General protein-ligand analysis  (run_protein_ligand_analysis)
"""

import os
import re
import json
import logging
import subprocess
from pathlib import Path
from typing import Optional

log = logging.getLogger(__name__)


def run_cyp_heme_analysis(
    work_dir,
    prmtop="cyp_heme.prmtop",
    axial_cys_resid=None,
    hem_resid=None,
    state="CPDI",
    config=None,
    **kw,
):
    """Generate cpptraj analysis script and Python plotting script.

    Args:
        work_dir: MD simulation directory (containing md_output/)
        prmtop: Topology file name
        axial_cys_resid: Residue ID of axial cysteine
        hem_resid: Residue ID of heme in output PDB
        state: Heme state (CPDI/DIOXY/IC6)

    Returns:
        dict with script paths, or error dict.
    """
    if not os.path.isdir(work_dir):
        return {"error": f"Directory not found: {work_dir}"}

    if axial_cys_resid is None or hem_resid is None:
        # Try to read from pipeline_result.json
        result_file = os.path.join(work_dir, "pipeline_result.json")
        if os.path.exists(result_file):
            import json

            with open(result_file, encoding="utf-8") as f:
                info = json.load(f)
            axial_cys_resid = axial_cys_resid or info.get("axial_cys")
            hem_resid = hem_resid or info.get("hem_resid")
            state = state or info.get("state", "CPDI")

    if axial_cys_resid is None or hem_resid is None:
        return {
            "error": "axial_cys_resid and hem_resid required",
            "hint": "Run amber_cyp_md first, or specify residue IDs manually",
        }

    try:
        analyze_path = _generate_cpptraj_script(
            work_dir, prmtop, axial_cys_resid, hem_resid, state
        )
        extract_path = _generate_extract_script(work_dir, prmtop)
        plot_path = _generate_plot_script(work_dir, axial_cys_resid, hem_resid, state)

        return {
            "analyze_script": analyze_path,
            "extract_script": extract_path,
            "plot_script": plot_path,
            "next_steps": [
                f"bash {analyze_path}",
                f"bash {extract_path}",
                f"python3 {plot_path}",
            ],
        }
    except Exception as e:
        return {"error": str(e), "hint": "Check work_dir and residue IDs"}


def _generate_cpptraj_script(output_dir, prmtop, axial_cys_resid, hem_resid, state):
    """Generate cpptraj analysis bash script."""
    if state == "CPDI":
        extra_dist = f"""
# Fe=O (Compound I oxo)
distance fe_o :{hem_resid}@FE :{hem_resid}@O1 out ${{OUTDIR}}/fe_o_dist.dat"""
    elif state == "DIOXY":
        extra_dist = f"""
# Fe-O1 and Fe-O2 (dioxygenated)
distance fe_o1 :{hem_resid}@FE :{hem_resid}@O1 out ${{OUTDIR}}/fe_o1_dist.dat
distance fe_o2 :{hem_resid}@FE :{hem_resid}@O2 out ${{OUTDIR}}/fe_o2_dist.dat"""
    else:
        extra_dist = ""

    script = f"""#!/bin/bash
# Trajectory analysis for CYP-heme MD
# Auto-generated by zhuangzhou/amber_md

source ~/amber25/amber.sh

WORKDIR="{output_dir}"
TOP="${{WORKDIR}}/{prmtop}"
TRAJ="${{WORKDIR}}/md_output/10_prod.nc"
OUTDIR="${{WORKDIR}}/analysis"
mkdir -p ${{OUTDIR}}

cpptraj <<EOF
parm ${{TOP}}
trajin ${{TRAJ}}

# Fe-S distance
distance fe_s :{axial_cys_resid}@SG :{hem_resid}@FE out ${{OUTDIR}}/fe_s_dist.dat
{extra_dist}

# Fe-N distances (porphyrin)
distance fe_na :{hem_resid}@FE :{hem_resid}@NA out ${{OUTDIR}}/fe_na_dist.dat
distance fe_nb :{hem_resid}@FE :{hem_resid}@NB out ${{OUTDIR}}/fe_nb_dist.dat
distance fe_nc :{hem_resid}@FE :{hem_resid}@NC out ${{OUTDIR}}/fe_nc_dist.dat
distance fe_nd :{hem_resid}@FE :{hem_resid}@ND out ${{OUTDIR}}/fe_nd_dist.dat

# Protein RMSD (Ca, mass-weighted)
rms first :1-{hem_resid - 1}@CA out ${{OUTDIR}}/rmsd_ca.dat mass

# Heme RMSD (heavy atoms, fitted to Ca)
rms first :1-{hem_resid - 1}@CA
rms first :{hem_resid}&!@H= out ${{OUTDIR}}/rmsd_heme.dat mass

# RMSF by residue
rms first :1-{hem_resid - 1}@CA
atomicfluct :1-{hem_resid - 1}@CA out ${{OUTDIR}}/rmsf_ca.dat byres

# Radius of gyration
radgyr :1-{hem_resid - 1} out ${{OUTDIR}}/radgyr.dat mass

run

# Export PDB frames
clear all
parm ${{TOP}}

# First frame
trajin ${{TRAJ}} 1 1
autoimage
strip :WAT,Na+,Cl-
trajout ${{OUTDIR}}/frame_first.pdb pdb
run
clear trajin

# Last frame
trajin ${{TRAJ}} lastframe
autoimage
strip :WAT,Na+,Cl-
trajout ${{OUTDIR}}/frame_last.pdb pdb
run
clear trajin

# Full trajectory PDB (solute only)
trajin ${{TRAJ}}
autoimage
strip :WAT,Na+,Cl-
trajout ${{OUTDIR}}/prod_traj.pdb pdb
run
EOF

echo "Analysis complete. Results in ${{OUTDIR}}/"
"""
    path = os.path.join(output_dir, "analyze.sh")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(script)
    return path


def _generate_extract_script(output_dir, prmtop):
    """Generate pre-MD structure extraction script."""
    inpcrd = prmtop.replace(".prmtop", ".inpcrd")
    script = f"""#!/bin/bash
# Extract pre-MD initial structure
source ~/amber25/amber.sh
WORKDIR="{output_dir}"
cpptraj <<EOF
parm ${{WORKDIR}}/{prmtop}
trajin ${{WORKDIR}}/{inpcrd}
autoimage
strip :WAT,Na+,Cl-
trajout ${{WORKDIR}}/analysis/pre_md_initial.pdb pdb
run
EOF
"""
    path = os.path.join(output_dir, "extract_initial.sh")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(script)
    return path


